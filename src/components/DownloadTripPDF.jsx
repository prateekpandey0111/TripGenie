
import { jsPDF } from "jspdf";
import { Download } from "lucide-react";

function DownloadTripPDF({ itinerary, tripDetails }) {
  function handleDownload() {
    if (!itinerary) return;

    const pdf = new jsPDF();

    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    const margin = 18;
    const contentWidth = pageWidth - margin * 2;

    let y = 20;

    // Add text with automatic page handling
    function addText(text, options = {}) {
      const {
        size = 10,
        color = [51, 65, 85],
        bold = false,
        gap = 5,
      } = options;

      pdf.setFont("helvetica", bold ? "bold" : "normal");
      pdf.setFontSize(size);
      pdf.setTextColor(...color);

      const lines = pdf.splitTextToSize(
        String(text || ""),
        contentWidth
      );

      const lineHeight = size * 0.45 + 2;
      const requiredHeight = lines.length * lineHeight + gap;

      if (y + requiredHeight > pageHeight - margin) {
        pdf.addPage();
        y = 20;
      }

      pdf.text(lines, margin, y);
      y += requiredHeight;
    }

    // Add a section heading
    function addHeading(text) {
      y += 5;

      if (y + 15 > pageHeight - margin) {
        pdf.addPage();
        y = 20;
      }

      pdf.setFillColor(6, 182, 212);
      pdf.roundedRect(margin, y - 5, contentWidth, 11, 2, 2, "F");

      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(11);
      pdf.setTextColor(255, 255, 255);
      pdf.text(text, margin + 4, y + 2);

      y += 13;
    }

    // Document header
    pdf.setFillColor(15, 23, 42);
    pdf.rect(0, 0, pageWidth, 55, "F");

    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(23);
    pdf.setTextColor(255, 255, 255);
    pdf.text("TRIPGENIE AI", margin, 22);

    pdf.setFontSize(10);
    pdf.setFont("helvetica", "normal");
    pdf.setTextColor(165, 243, 252);
    pdf.text("YOUR PERSONALIZED TRAVEL ITINERARY", margin, 32);

    y = 68;

    // Trip title and overview
    addText(itinerary.title || "Your Travel Itinerary", {
      size: 18,
      bold: true,
      color: [15, 23, 42],
      gap: 8,
    });

    addText(itinerary.overview, {
      size: 10,
      color: [71, 85, 105],
      gap: 8,
    });

    // Trip details
    addHeading("TRIP DETAILS");

    addText(`Destination: ${tripDetails.destination}`);
    addText(`Duration: ${tripDetails.duration} days`);
    addText(`Travellers: ${tripDetails.travelers}`);
    addText(`Budget category: ${tripDetails.budget}`, {
      gap: 8,
    });

    // Daily itinerary
    addHeading("DAY-WISE ITINERARY");

    (itinerary.dailyItinerary || []).forEach((day, index) => {
      addText(
        `DAY ${day.day || index + 1}: ${day.title || "Explore"}`,
        {
          size: 12,
          bold: true,
          color: [8, 145, 178],
          gap: 5,
        }
      );

      (day.activities || []).forEach((activity) => {
        addText(`${activity.time || "Activity"} - ${activity.place}`, {
          size: 10,
          bold: true,
          color: [30, 41, 59],
          gap: 2,
        });

        addText(activity.description, {
          size: 9,
          color: [71, 85, 105],
          gap: 5,
        });
      });

      y += 3;
    });

    // Estimated budget
    if (itinerary.estimatedBudget) {
      addHeading("ESTIMATED TRIP BUDGET");

      addText(`Total estimated cost: ${itinerary.estimatedBudget.total}`, {
        bold: true,
      });

      addText(
        `Estimated cost per person: ${itinerary.estimatedBudget.perPerson}`,
        { bold: true, gap: 5 }
      );

      addText(
        "Note: These are AI-generated estimates, not live-verified prices.",
        { size: 9, color: [100, 116, 139] }
      );
    }

    // Travel tips
    if (itinerary.travelTips?.length > 0) {
      addHeading("TRAVEL TIPS");

      itinerary.travelTips.forEach((tip, index) => {
        addText(`${index + 1}. ${tip}`, {
          size: 9,
          gap: 4,
        });
      });
    }

    // Footer on every page
    const totalPages = pdf.internal.getNumberOfPages();

    for (let page = 1; page <= totalPages; page++) {
      pdf.setPage(page);

      pdf.setDrawColor(226, 232, 240);
      pdf.line(
        margin,
        pageHeight - 13,
        pageWidth - margin,
        pageHeight - 13
      );

      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(8);
      pdf.setTextColor(100, 116, 139);

      pdf.text(
        "Generated by TripGenie AI",
        margin,
        pageHeight - 7
      );

      pdf.text(
        `Page ${page} of ${totalPages}`,
        pageWidth - margin,
        pageHeight - 7,
        { align: "right" }
      );
    }

    // Download the PDF
    const fileName = `TripGenie-${tripDetails.destination
      .trim()
      .replace(/\s+/g, "-")}-Itinerary.pdf`;

    pdf.save(fileName);
  }

  return (
    <button
      type="button"
      onClick={handleDownload}
      className="inline-flex items-center justify-center gap-2 bg-cyan-300 hover:bg-cyan-400 text-slate-900 font-semibold px-7 py-3 rounded-full transition-colors"
    >
      <Download size={18} />
      Download Trip PDF
    </button>
  );
}

export default DownloadTripPDF;
